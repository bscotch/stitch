/**
 * @file Parse the usage text that Igor prints (along with exit code 127)
 * when given an unknown option such as `--help`. Used to generate the
 * Igor CLI types, see `scripts/generate-igor-types.mts`.
 */

export interface IgorHelpOption {
  /** The name used as the key in option objects (the longest name) */
  key: string;
  /** Every name for this option, without dashes, as listed by Igor */
  names: string[];
  /** The flag to emit for this option, e.g. `--runtimePath` or `-j` */
  flag: string;
  takesValue: boolean;
  description: string;
}

export interface IgorHelp {
  options: IgorHelpOption[];
  /** Commands per worker, in the order Igor lists them */
  workers: Record<string, string[]>;
}

export function parseIgorHelp(text: string): IgorHelp {
  const lines = text.replace(/\r\n?/g, '\n').split('\n');
  const optionsStart = lines.findIndex((l) => l.trim() === 'Options:');
  const workersStart = lines.findIndex((l) =>
    l.startsWith('Supported Workers and Commands'),
  );
  if (optionsStart < 0 || workersStart < 0) {
    throw new Error(
      'Could not find the "Options:" and "Supported Workers and Commands" sections in the Igor usage text',
    );
  }

  // Options: each starts with whitespace + '-', descriptions may wrap onto
  // more-indented continuation lines, and the description may start on the
  // next line when the names are long.
  const options: IgorHelpOption[] = [];
  let current: IgorHelpOption | undefined;
  for (const line of lines.slice(optionsStart + 1, workersStart)) {
    const optionMatch = line.match(/^\s{1,8}(-[^\s].*?)(?:\s{2,}(.*))?$/);
    if (optionMatch && /^\s{1,8}-/.test(line)) {
      const [, namesPart, description = ''] = optionMatch;
      const takesValue = /=VALUE\b/.test(namesPart);
      const names = namesPart
        .split(',')
        .map((n) =>
          n
            .trim()
            .replace(/=VALUE$/, '')
            .replace(/^-+/, ''),
        )
        .filter(Boolean);
      const key = names.reduce((a, b) => (b.length > a.length ? b : a));
      current = {
        key,
        names,
        flag: key.length === 1 ? `-${key}` : `--${key}`,
        takesValue,
        description: description.trim(),
      };
      options.push(current);
    } else if (current && line.trim()) {
      current.description = `${current.description} ${line.trim()}`.trim();
    }
  }

  const workers: Record<string, string[]> = {};
  for (const line of lines.slice(workersStart + 1)) {
    const match = line.match(/^(\w+)\s+(\w+)\s*$/);
    if (!match) continue;
    const [, worker, command] = match;
    workers[worker] ||= [];
    workers[worker].push(command);
  }
  return { options, workers };
}

/** Render the TypeScript source for the generated Igor CLI types */
export function renderIgorTypes(help: IgorHelp, source: string): string {
  const q = (s: string) => JSON.stringify(s);
  const workerNames = Object.keys(help.workers);
  const out: string[] = [
    '/**',
    ` * @file GENERATED by scripts/generate-igor-types.mts from ${source}.`,
    ' * Do not edit by hand: re-run the script against a newer Igor instead.',
    ' */',
    '',
    '/** Igor workers (build targets, plus the `tests` and `runtime` utilities) */',
    `export const igorWorkers = [${workerNames.map(q).join(', ')}] as const;`,
    'export type IgorWorker = (typeof igorWorkers)[number];',
    '',
    '/** The commands each Igor worker supports */',
    'export const igorCommands = {',
    ...workerNames.map(
      (w) => `  ${w}: [${help.workers[w].map(q).join(', ')}],`,
    ),
    '} as const satisfies Record<IgorWorker, readonly string[]>;',
    'export type IgorCommandName<W extends IgorWorker = IgorWorker> =',
    '  (typeof igorCommands)[W][number];',
    '',
    '/** Igor command-line options, keyed by their longest name */',
    'export interface IgorCliOptions {',
  ];
  for (const option of help.options) {
    const aliases =
      option.names.length > 1
        ? ` (aliases: ${option.names.filter((n) => n !== option.key).join(', ')})`
        : '';
    out.push(
      `  /** ${option.description.replace(/\*\//g, '*\\/')}${aliases} */`,
    );
    const key = /^[A-Za-z_$][\w$]*$/.test(option.key)
      ? option.key
      : q(option.key);
    out.push(
      `  ${key}?: ${option.takesValue ? 'string | number' : 'boolean'};`,
    );
  }
  out.push('}', '');
  out.push(
    '/** How each option is passed on the command line */',
    'export const igorOptionFlags = {',
    ...help.options.map(
      (o) =>
        `  ${/^[A-Za-z_$][\w$]*$/.test(o.key) ? o.key : q(o.key)}: { flag: ${q(o.flag)}, takesValue: ${o.takesValue} },`,
    ),
    '} as const satisfies Record<keyof IgorCliOptions, { flag: string; takesValue: boolean }>;',
    '',
  );
  return out.join('\n');
}
